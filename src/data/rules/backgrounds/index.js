const toolChoices = {
  artisan: ["calligraphers-supplies", "carpenters-tools", "cartographers-tools"],
  gaming: ["gaming-set"],
  instrument: ["musical-instrument"],
};

const background = ({
  id,
  name,
  label,
  abilityOptions,
  featId,
  skills,
  tool,
  toolChoice,
  equipment,
  gp,
  summary,
}) => {
  const choices = toolChoice
    ? [
        {
          id: `${id}-${toolChoice}-choice`,
          label: `Herramienta de ${label}`,
          type: toolChoice === "artisan" ? "artisanTool" : toolChoice === "gaming" ? "gamingSet" : "musicalInstrument",
          count: 1,
          from: toolChoices[toolChoice],
        },
      ]
    : [];

  return {
    id,
    name,
    label,
    source: "Player's Handbook 2024",
    summary,
    abilityOptions,
    grants: {
      featId,
      skills,
      tool: tool || `${toolChoice}-choice`,
      equipment,
      coins: { gp },
    },
    equipmentOptions: [
      { id: `${id}-package`, label: "Equipo inicial", equipment, coins: { gp } },
      { id: `${id}-gold`, label: "50 PO", equipment: [], coins: { gp: 50 } },
    ],
    choices,
    effects: [
      { type: "feat.grant", featId },
      { type: "proficiency.skill", items: skills },
      ...(tool ? [{ type: "proficiency.tool", items: [tool] }] : []),
      { type: "equipment.grant", items: equipment },
      { type: "coin.add", coins: { gp } },
    ],
    sheetText: `${label}: ${skills.join(", ")}; dote ${featId}.`,
  };
};

