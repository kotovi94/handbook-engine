const gear = (id, name, label, category = "gear", options = {}) => ({
  id,
  name,
  label,
  category,
  summary: options.summary || label,
  description: options.description || options.summary || label,
  cost: options.cost,
  weight: options.weight,
  effects: options.effects || [],
  sheetText: options.sheetText || label,
  ...options.extra,
});

const weapon = (id, name, label, ability, damage, damageLabel, options = {}) => ({
  id,
  name,
  label,
  category: "weapon",
  summary: options.summary || `${label}: ${damageLabel}.`,
  description: options.description || `${label}: ${damageLabel}.`,
  ability,
  damage,
  damageLabel,
  range: options.range,
  properties: options.properties || [],
  cost: options.cost,
  weight: options.weight,
  effects: [],
  sheetText: options.sheetText || label,
  mastery: options.mastery,
  weaponGroup: options.weaponGroup,
});

const armor = (id, name, label, armorType, options = {}) => ({
  id,
  name,
  label,
  category: "armor",
  summary: options.summary || label,
  description: options.description || options.summary || label,
  ac: options.ac,
  acBase: options.acBase,
  dexterity: options.dexterity,
  armorType,
  cost: options.cost,
  weight: options.weight,
  effects: options.ac
    ? [{ type: "armor.ac", value: options.ac }]
    : [{ type: "armor.acBase", value: options.acBase, dexterity: options.dexterity }],
  sheetText: label,
  strengthRequirement: options.strengthRequirement,
  stealthDisadvantage: Boolean(options.stealthDisadvantage),
});

