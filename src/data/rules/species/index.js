const trait = (id, name, label, sheetText) => ({
  id,
  name,
  label,
  description: sheetText,
  effects: [],
  sheetText,
});

const languageChoice = (id) => ({
  id: `${id}-languages`,
  label: "Idiomas de origen",
  type: "language",
  count: 2,
  from: standardLanguages,
});

const sizeChoice = (id) => ({
  id: `${id}-size`,
  label: "Tamaño de especie",
  type: "speciesSize",
  count: 1,
  from: ["Small", "Medium"],
  optionLabels: {
    Small: "Pequeño",
    Medium: "Mediano",
  },
});

const speciesBase = ({ id, name, label, summary, size, speed, choices = [], effects = [], traits, advice }) => ({
  id,
  name,
  label,
  summary,
  guide: {
    advice,
  },
  creatureType: "Humanoid",
  size,
  speed,
  languages: ["Common"],
  choices: [languageChoice(id), ...choices],
  effects: [
    { type: "speed.set", value: speed },
    { type: "language.grant", languages: ["Common"] },
    { type: "trait.grant", items: traits.map((item) => item.name) },
    ...effects,
  ],
  grants: {
    traits,
    sheetNotes: ["Anota estos rasgos en Features & Traits."],
  },
});

